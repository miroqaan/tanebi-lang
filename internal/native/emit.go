package native

import (
	"encoding/hex"
	"fmt"
	"strconv"
	"strings"
	"unicode"
)

func rustName(name string) string {
	ascii := true
	for _, r := range name {
		if r > 127 {
			ascii = false
			break
		}
	}
	if ascii && !strings.HasPrefix(name, "__") {
		return "tn_" + name
	}
	// Reserve all double-underscore source names as well as the Unicode tag,
	// keeping the encoding injective without changing ordinary ABI/test names.
	if ascii {
		return "tn___a_" + hex.EncodeToString([]byte(name))
	}
	return "tn___u_" + hex.EncodeToString([]byte(name))
}
func rustType(t string) string {
	switch t {
	case "str":
		return "&'static str"
	case "void":
		return "()"
	default:
		return t
	}
}
func rustLocal(name string) string { return "tn___local_" + rustName(name) }
func rustString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if unicode.IsControl(r) {
				fmt.Fprintf(&b, `\u{%x}`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}
func rustConstant(v constant) string {
	switch v.typ {
	case "str":
		return rustString(v.s)
	case "bool":
		return strconv.FormatBool(v.b)
	default:
		return fmt.Sprintf("%du64", v.n)
	}
}

func (c *compiler) emit() string {
	var b strings.Builder
	b.WriteString("// Generated by the TANEBI systems compiler. Do not edit.\n")
	if c.options.Target == "uefi" {
		b.WriteString("#![no_std]\n#![no_main]\n")
	}
	b.WriteString("#![allow(non_snake_case, non_upper_case_globals, unused_mut, unused_variables, dead_code, unused_parens, unreachable_code, unsafe_op_in_unsafe_fn)]\n\n")
	for _, d := range c.decls {
		n := rustName(d.name)
		switch d.kind {
		case "const":
			fmt.Fprintf(&b, "pub const %s: %s = %s;\n", n, rustType(d.typ), rustConstant(c.constants[d.name]))
		case "global":
			fmt.Fprintf(&b, "pub static mut %s: %s = %s;\n", n, rustType(d.typ), rustConstant(c.constants[d.name]))
		case "buffer":
			fmt.Fprintf(&b, "#[repr(C, align(16))]\npub struct __tn_buffer_%s(pub [u8; %d]);\npub static mut %s: __tn_buffer_%s = __tn_buffer_%s([0; %d]);\n", n, c.sizes[d.name], n, n, n, c.sizes[d.name])
		case "embed":
			fmt.Fprintf(&b, "pub static %s: &[u8; %d] = include_bytes!(%s);\n", n, c.sizes[d.name], rustString(c.assets[d.name]))
		}
	}
	b.WriteString("\n")
	for _, d := range c.decls {
		if d.kind != "fn" {
			continue
		}
		fmt.Fprintf(&b, "// %s:%d\npub unsafe fn %s(", strings.ReplaceAll(strings.ReplaceAll(d.pos.file, "\r", " "), "\n", " "), d.pos.line, rustName(d.name))
		for n, p := range d.params {
			if n > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "mut %s: %s", rustLocal(p.name), rustType(p.typ))
		}
		fmt.Fprintf(&b, ") -> %s {\n", rustType(d.typ))
		c.emitBlock(&b, d.body, 1)
		b.WriteString("}\n\n")
	}
	emitRuntime(&b)
	if c.options.Target == "uefi" {
		fmt.Fprintf(&b, "\n#[unsafe(no_mangle)]\npub extern \"efiapi\" fn efi_main(image: usize, st: usize) -> usize {\n    unsafe { %s(image as u64, st as u64) as usize }\n}\n", rustName(c.options.Entry))
		b.WriteString("#[panic_handler]\nfn __tn_panic(_: &core::panic::PanicInfo) -> ! { loop { core::hint::spin_loop(); } }\n")
	} else if c.options.Target == "host" {
		fmt.Fprintf(&b, "\nfn main() { unsafe { self::%s(); } }\n", rustName(c.options.Entry))
	}
	return b.String()
}
func (c *compiler) emitBlock(b *strings.Builder, ss []*stmt, level int) {
	indent := strings.Repeat("    ", level)
	for _, s := range ss {
		b.WriteString(indent)
		switch s.kind {
		case "let":
			fmt.Fprintf(b, "let mut %s: %s = %s;\n", rustLocal(s.name), rustType(s.typ), c.emitExpr(s.value))
		case "assign":
			target := rustName(s.name)
			if s.local {
				target = rustLocal(s.name)
			}
			rhs := c.emitExpr(s.value)
			switch s.op {
			case "+=":
				rhs = "(" + target + ").wrapping_add(" + rhs + ")"
			case "-=":
				rhs = "(" + target + ").wrapping_sub(" + rhs + ")"
			case "|=":
				rhs = "(" + target + " | " + rhs + ")"
			case "&=":
				rhs = "(" + target + " & " + rhs + ")"
			}
			fmt.Fprintf(b, "%s = %s;\n", target, rhs)
		case "expr":
			fmt.Fprintf(b, "%s;\n", c.emitExpr(s.value))
		case "return":
			if s.value == nil {
				b.WriteString("return;\n")
			} else {
				fmt.Fprintf(b, "return %s;\n", c.emitExpr(s.value))
			}
		case "break", "continue":
			b.WriteString(s.kind + ";\n")
		case "while":
			if s.condition.kind == "bool" && s.condition.name == "true" {
				b.WriteString("loop {\n")
			} else {
				fmt.Fprintf(b, "while %s {\n", c.emitExpr(s.condition))
			}
			c.emitBlock(b, s.body, level+1)
			b.WriteString(indent + "}\n")
		case "if":
			fmt.Fprintf(b, "if %s {\n", c.emitExpr(s.condition))
			c.emitBlock(b, s.body, level+1)
			b.WriteString(indent + "}")
			if len(s.other) > 0 {
				b.WriteString(" else {\n")
				c.emitBlock(b, s.other, level+1)
				b.WriteString(indent + "}")
			}
			b.WriteByte('\n')
		}
	}
}
func (c *compiler) emitExpr(x *expr) string {
	switch x.kind {
	case "number":
		return fmt.Sprintf("%du64", x.number)
	case "string":
		return rustString(x.text)
	case "bool":
		return x.name
	case "name":
		if x.local {
			return rustLocal(x.name)
		}
		return rustName(x.name)
	case "unary":
		a := c.emitExpr(x.args[0])
		switch x.name {
		case "!", "~":
			return "(!(" + a + "))"
		case "-":
			return "(" + a + ").wrapping_neg()"
		default:
			return "(" + a + ")"
		}
	case "binary":
		a, b := c.emitExpr(x.args[0]), c.emitExpr(x.args[1])
		method := map[string]string{"+": "wrapping_add", "-": "wrapping_sub", "*": "wrapping_mul", "/": "wrapping_div", "%": "wrapping_rem", "<<": "wrapping_shl", ">>": "wrapping_shr"}[x.name]
		if method != "" {
			if x.name == "<<" || x.name == ">>" {
				b = "(" + b + ") as u32"
			}
			return "(" + a + ")." + method + "(" + b + ")"
		}
		return "(" + a + " " + x.name + " " + b + ")"
	case "call":
		if x.name == "print" || x.name == "println" {
			return "::std::" + x.name + "!(\"{}\", " + c.emitExpr(x.args[0]) + ")"
		}
		if x.name == "config" {
			return fmt.Sprintf("%du64", c.options.Defines[x.args[0].text])
		}
		if x.name == "addr" || x.name == "len" {
			a := x.args[0]
			if a.typ == "memory" {
				d := c.symbols[a.name]
				if x.name == "len" {
					return fmt.Sprintf("%du64", c.sizes[a.name])
				}
				if d.kind == "buffer" {
					return "(core::ptr::addr_of_mut!(" + rustName(a.name) + ".0) as *mut u8 as u64)"
				}
				return "(" + rustName(a.name) + ".as_ptr() as u64)"
			}
			s := c.emitExpr(a)
			if x.name == "len" {
				return "((" + s + ").len() as u64)"
			}
			return "((" + s + ").as_ptr() as u64)"
		}
		name := "self::" + rustName(x.name)
		if _, ok := builtin(x.name); ok {
			name = "__tn_" + x.name
		}
		args := make([]string, len(x.args))
		for n, a := range x.args {
			args[n] = c.emitExpr(a)
		}
		return name + "(" + strings.Join(args, ", ") + ")"
	}
	panic("validated expression is not supported")
}
func emitRuntime(b *strings.Builder) {
	b.WriteString(`// Generic x86-64 CPU, ABI, and memory primitives; no OS application logic.
// Port I/O intentionally retains the asm memory clobber: DMA setup must not
// move ordinary buffer writes across the hardware start/stop operation.
#[inline(always)] unsafe fn __tn_in8(port:u64)->u64 { let value:u8; core::arch::asm!("in al, dx", in("dx") port as u16, out("al") value, options(nostack, preserves_flags)); value as u64 }
#[inline(always)] unsafe fn __tn_out8(port:u64,value:u64) { core::arch::asm!("out dx, al", in("dx") port as u16, in("al") value as u8, options(nostack, preserves_flags)); }
#[inline(always)] unsafe fn __tn_out32(port:u64,value:u64) { core::arch::asm!("out dx, eax", in("dx") port as u16, in("eax") value as u32, options(nostack, preserves_flags)); }
#[inline(always)] unsafe fn __tn_load8(addr:u64)->u64 { core::ptr::read_volatile(addr as *const u8) as u64 }
#[inline(always)] unsafe fn __tn_store8(addr:u64,value:u64) { core::ptr::write_volatile(addr as *mut u8, value as u8); }
#[inline(always)] unsafe fn __tn_ticks()->u64 { let lo:u32; let hi:u32; core::arch::asm!("rdtsc", out("eax") lo, out("edx") hi, options(nomem, nostack)); ((hi as u64)<<32)|(lo as u64) }
#[inline(always)] unsafe fn __tn_pause() { core::hint::spin_loop(); }
#[inline(always)] unsafe fn __tn_irq_disable() { core::arch::asm!("cli", options(nostack)); }
#[inline(always)] unsafe fn __tn_byte(value:&str,index:u64)->u64 { value.as_bytes().get(index as usize).copied().unwrap_or(0) as u64 }
// copy has memmove semantics, including overlapping regions.
#[inline(always)] unsafe fn __tn_copy(dst:u64,src:u64,len:u64) {
    if dst > src && dst.wrapping_sub(src) < len {
        let mut n = len;
        while n != 0 { n -= 1; __tn_store8(dst.wrapping_add(n), __tn_load8(src.wrapping_add(n))); }
    } else {
        core::arch::asm!("cld", "rep movsb", inout("rdi") dst => _, inout("rsi") src => _, inout("rcx") len => _, options(nostack));
    }
}
#[inline(always)] unsafe fn __tn_zero(dst:u64,len:u64) { core::arch::asm!("cld", "rep stosb", inout("rdi") dst => _, inout("rcx") len => _, in("al") 0u8, options(nostack)); }
`)
	for _, bits := range []int{16, 32, 64} {
		size := bits / 8
		fmt.Fprintf(b, `#[inline(always)] unsafe fn __tn_load%d(addr:u64)->u64 {
    if addr & %d == 0 { core::ptr::read_volatile(addr as *const u%d) as u64 }
    else { let mut value = 0u64; let mut n = 0u64; while n < %d { value |= __tn_load8(addr.wrapping_add(n)) << (n*8); n += 1; } value }
}
#[inline(always)] unsafe fn __tn_store%d(addr:u64,value:u64) {
    if addr & %d == 0 { core::ptr::write_volatile(addr as *mut u%d,value as u%d); }
    else { let mut n = 0u64; while n < %d { __tn_store8(addr.wrapping_add(n),value >> (n*8)); n += 1; } }
}
`, bits, size-1, bits, size, bits, size-1, bits, bits, size)
	}
	for n := 0; n <= 6; n++ {
		params := []string{"ptr:u64"}
		types := []string{}
		args := []string{}
		for a := 0; a < n; a++ {
			params = append(params, fmt.Sprintf("a%d:u64", a))
			types = append(types, "usize")
			args = append(args, fmt.Sprintf("a%d as usize", a))
		}
		fmt.Fprintf(b, "#[inline(always)] unsafe fn __tn_call%d(%s)->u64 { let f: unsafe extern \"efiapi\" fn(%s)->usize = core::mem::transmute(ptr as usize); f(%s) as u64 }\n", n, strings.Join(params, ","), strings.Join(types, ","), strings.Join(args, ","))
	}
}
